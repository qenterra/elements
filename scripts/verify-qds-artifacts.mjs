#!/usr/bin/env node

import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const defaultRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = 'src/qds/qds-tokens.source.css'
const artifactPaths = ['site/qds-web.css', 'src/qds/qds-tokens.css']
const manifestPath = 'src/qds/qds-artifacts-manifest.json'
const generatedHeader = '/* Generated by scripts/verify-qds-artifacts.mjs. Do not edit. */\n'

function sha256(value) {
  return createHash('sha256').update(value).digest('hex')
}

function fileRecord(path, value) {
  return { path, sha256: sha256(value), bytes: value.byteLength }
}

function expectedState(projectRoot) {
  const source = readFileSync(join(projectRoot, sourcePath))
  const sourceText = source.toString('utf8')
  const firstLines = sourceText.split(/\r?\n/).slice(0, 8).join('\n')
  if (/generated by|@generated|<auto-generated/i.test(firstLines)) {
    throw new Error('The canonical QDS token source must be human-maintained, not generated output')
  }
  const version = sourceText.match(/QenTerra Design System ([0-9.]+)/)?.[1]
  if (!version)
    throw new Error('The canonical QDS token source has no pinned Design System version')

  const artifact = Buffer.concat([Buffer.from(generatedHeader), source])
  const values = new Map([[sourcePath, source]])
  for (const path of artifactPaths) values.set(path, artifact)

  const manifest = {
    schemaVersion: 1,
    version,
    repository: 'https://github.com/qenterra/elements',
    files: [...values]
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([path, value]) => fileRecord(path, value)),
  }
  return { artifact, manifest, source, version }
}

export function writeQdsArtifacts(projectRoot = defaultRoot) {
  const state = expectedState(projectRoot)
  for (const path of artifactPaths) writeFileSync(join(projectRoot, path), state.artifact)
  writeFileSync(join(projectRoot, manifestPath), `${JSON.stringify(state.manifest, null, 2)}\n`)
  return state
}

export function verifyQdsArtifacts(projectRoot = defaultRoot) {
  const state = expectedState(projectRoot)
  for (const path of artifactPaths) {
    const actual = readFileSync(join(projectRoot, path))
    if (!actual.equals(state.artifact)) {
      throw new Error(`Generated QDS artifact does not match its canonical source: ${path}`)
    }
  }

  const actualManifest = JSON.parse(readFileSync(join(projectRoot, manifestPath), 'utf8'))
  if (JSON.stringify(actualManifest) !== JSON.stringify(state.manifest)) {
    throw new Error('QDS artifact manifest does not match regenerated source and output bytes')
  }
  return {
    version: state.version,
    tokenCount: new Set(
      [...state.source.toString('utf8').matchAll(/--qds-[a-z0-9-]+(?=\s*:)/gi)].map(
        (match) => match[0],
      ),
    ).size,
    hash: sha256(state.artifact),
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const wroteArtifacts = process.argv.includes('--write')
  if (wroteArtifacts) writeQdsArtifacts()
  const result = verifyQdsArtifacts()
  console.log(
    `${wroteArtifacts ? 'Generated' : 'Verified'} QDS artifacts ${result.version}: ${result.tokenCount} tokens, ${result.hash}.`,
  )
}
